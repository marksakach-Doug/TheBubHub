// The instrument behind Clicker's Instrument and Sequencer modes: real
// samples, taken out of a SoundFont and played back like a small sampler.
//
// Why not an oscillator: a triangle wave tells you the pitch and nothing
// else. A sample of a piano tells you the pitch AND that it is a piano, and
// this is a musical memory game - the timbre is half of what the player is
// remembering.
//
// How it works:
//   * games/clicker/samples/bank.js is the manifest. For every note it says
//     which file plays it, the key that file was recorded at, how far off
//     that file actually is, and where a sustaining voice loops. It is
//     generated by games/clicker/tools/extract_sf2.py.
//   * a note is played by finding the sample whose key list holds the note
//     and running it at the rate that puts it back on the right pitch.
//   * a voice that is still downloading is not played: the caller keeps its
//     oscillators, so the player hears a tone instead of nothing.
//
// Nothing here holds state outside the factory, so the hub can mount and
// unmount the game as often as it likes.
import { BANK } from './samples/bank.js';

// A piano transient reads louder than the sine it replaces, so it is
// trimmed back; the electric piano and the Wurlitzer sit where they are.
const TRIM = { piano: 0.75, rhodes: 1, wurly: 0.9 };

// The attack of a note, in seconds. Fast enough to feel like the grid.
const ATTACK = 0.005;

// The pitch of a frequency, in MIDI numbers.
export function midiOf(freq) {
  return 69 + 12 * Math.log(freq / 440) / Math.LN2;
}

// Which sample plays a note: the one whose key list holds it, or - for a
// note the bank does not cover - the one recorded nearest to it.
export function pickSample(voice, midi) {
  const bank = BANK[voice];
  if (!bank || !bank.samples.length) return null;
  for (let i = 0; i < bank.samples.length; i++) {
    if (bank.samples[i].keys.indexOf(midi) >= 0) return bank.samples[i];
  }
  let best = null;
  let bestDist = 0;
  for (let i = 0; i < bank.samples.length; i++) {
    const d = Math.abs(midi - bank.samples[i].rootKey);
    if (!best || d < bestDist) { best = bank.samples[i]; bestDist = d; }
  }
  return best;
}

// The playback rate that turns a sample recorded at its root key into the
// note asked for. The manifest's cents are that sample's own tuning error,
// measured out of the audio when it was extracted, so a note that was
// recorded 50 cents flat still plays in tune.
export function rateFor(midi, sample) {
  const semis = (midi - sample.rootKey) + (sample.cents || 0) / 100;
  return Math.pow(2, semis / 12);
}

// How long a note rings after it is struck. A piano keeps ringing after the
// game has moved on, and cutting it dead would sound like a click.
function releaseFor(dur) {
  return Math.min(0.35, Math.max(0.08, dur * 0.5));
}

export function createSampler() {
  const decoded = {};        // url -> AudioBuffer
  const fetched = {};        // voice -> ArrayBuffer[]
  const loading = {};        // voice -> Promise (the fetch)
  const decoding = {};       // url -> true, so nothing is decoded twice
  const live = [];           // sources still playing
  let ac = null;
  let dead = false;

  function samplesOf(voice) {
    const bank = BANK[voice];
    return bank ? bank.samples : [];
  }

  // Fetch a voice's files. Same origin, hashed by the build, and the browser
  // keeps them for next time - so the second visit to Clicker is silent
  // about the download.
  function loadVoice(voice) {
    if (dead || loading[voice]) return;
    const bank = BANK[voice];
    if (!bank) return;
    loading[voice] = Promise.all(bank.samples.map((s) =>
      fetch(s.url)
        .then((r) => (r && r.ok ? r.arrayBuffer() : null))
        .catch(() => null)
    )).then((bytes) => {
      fetched[voice] = bytes;
      decodeVoice(voice, bytes);
    });
  }

  // Turn fetched bytes into audio the browser can play. decodeAudioData
  // needs a context, and it takes the bytes apart as it reads them - so a
  // sample is only ever decoded once, however many times we are asked.
  function decodeVoice(voice, bytes) {
    if (!ac || dead || !bytes) return;
    const list = samplesOf(voice);
    for (let i = 0; i < list.length; i++) {
      const url = list[i].url;
      const data = bytes[i];
      if (!data || decoding[url]) continue;
      decoding[url] = true;
      Promise.resolve(ac.decodeAudioData(data)).then((buffer) => {
        if (!dead) decoded[url] = buffer;
      }).catch(() => {
        decoding[url] = false;    // a note that will not decode stays silent
      });
    }
  }

  // Hand the sampler the audio context. Called the moment the game has one,
  // which is inside the player's first tap - a context cannot be made before
  // that and be heard.
  function attach(context) {
    if (dead || !context || ac === context) return;
    ac = context;
    Object.keys(fetched).forEach((voice) => decodeVoice(voice, fetched[voice]));
  }

  function ready(voice) {
    const list = samplesOf(voice);
    if (!list.length) return false;
    for (let i = 0; i < list.length; i++) {
      if (!decoded[list[i].url]) return false;
    }
    return true;
  }

  // Play one note. Returns false when the sample is not here yet, so the
  // caller can fall back to its oscillator.
  function play(freq, opts) {
    const o = opts || {};
    const voice = o.voice || 'piano';
    const midi = midiOf(freq);
    const sample = pickSample(voice, midi);
    if (!sample) return false;
    const buffer = decoded[sample.url];
    if (!buffer || !ac) {
      loadVoice(voice);
      return false;
    }
    const dur = o.dur == null ? 0.3 : o.dur;
    const rel = releaseFor(dur);
    const peak = (o.gain == null ? 0.22 : o.gain) * (TRIM[voice] || 1);
    const t = ac.currentTime + (o.delay || 0);

    const src = ac.createBufferSource();
    src.buffer = buffer;
    src.playbackRate.value = rateFor(midi, sample);
    const g = ac.createGain();
    g.gain.setValueAtTime(0.0001, t);
    g.gain.linearRampToValueAtTime(peak, t + ATTACK);
    g.gain.setValueAtTime(peak, t + Math.max(ATTACK, dur));
    g.gain.linearRampToValueAtTime(0.0001, t + dur + rel);
    src.connect(g);
    g.connect(ac.destination);
    src.start(t);
    src.stop(t + dur + rel + 0.02);
    live.push(src);
    return true;
  }

  // Hold a note ringing until it is released - the Split mode's two voices.
  // The Wurlitzer samples carry a sustain loop, so the note does not run
  // out; a voice without a loop just plays to the end of its sample.
  function hold(freq, opts) {
    const o = opts || {};
    const voice = o.voice || 'wurly';
    const midi = midiOf(freq);
    const sample = pickSample(voice, midi);
    if (!sample) return null;
    const buffer = decoded[sample.url];
    if (!buffer || !ac) {
      loadVoice(voice);
      return null;
    }
    const src = ac.createBufferSource();
    src.buffer = buffer;
    src.playbackRate.value = rateFor(midi, sample);
    if (sample.loopEnd > sample.loopStart) {
      src.loop = true;
      // The frames are exact; the seconds in the manifest are rounded for
      // humans. A loop point a frame or two out is a click every time round.
      if (sample.loopEndFrame) {
        src.loopStart = sample.loopStartFrame / sample.rate;
        src.loopEnd = sample.loopEndFrame / sample.rate;
      } else {
        src.loopStart = sample.loopStart;
        src.loopEnd = sample.loopEnd;
      }
    }
    const g = ac.createGain();
    const peak = (o.gain == null ? 0.2 : o.gain) * (TRIM[voice] || 1);
    const t = ac.currentTime;
    g.gain.setValueAtTime(0.0001, t);
    g.gain.linearRampToValueAtTime(peak, t + 0.02);
    src.connect(g);
    g.connect(ac.destination);
    src.start(t);
    live.push(src);

    let done = false;
    return {
      release(fade) {
        if (done) return;
        done = true;
        const f = fade == null ? 0.25 : fade;
        const n = ac.currentTime;
        try {
          g.gain.cancelScheduledValues(n);
          g.gain.setValueAtTime(Math.max(g.gain.value, 0.0001), n);
          g.gain.linearRampToValueAtTime(0.0001, n + f);
          src.stop(n + f + 0.02);
        } catch (e) { /* the source may already have stopped */ }
      }
    };
  }

  function dispose() {
    dead = true;
    for (let i = 0; i < live.length; i++) {
      try { live[i].stop(); } catch (e) { /* already stopped */ }
    }
    live.length = 0;
  }

  return { attach, loadVoice, ready, play, hold, dispose, midiOf, pickSample, rateFor };
}
